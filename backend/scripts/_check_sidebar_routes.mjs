/**
 * Sidebar link audit: every `to` in each role's sidebar must resolve to a declared <Route path>,
 * and no role may list the same destination twice.
 * Run: node backend/scripts/_check_sidebar_routes.mjs   (exit code 1 when a problem is found)
 */
import { readdirSync, readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const sidebar = await import(new URL('../../src/Common/CommonSidebar/Components/sidebarLinks.js', import.meta.url))

const routeFiles = [
    ...readdirSync(join(root, 'src', 'Routes')).map((name) => join(root, 'src', 'Routes', name)),
    join(root, 'src', 'App.jsx'),
]
const routes = new Set()
for (const file of routeFiles) {
    const text = readFileSync(file, 'utf8')
    for (const match of text.matchAll(/path\s*=\s*["'{`]+([^"'`}]+)["'`}]/g)) routes.add(match[1].trim())
    // Routes generated by src/Common/staffCommonRoutes.jsx
    for (const match of text.matchAll(/staffCommonRoutes\('([^']+)'[^)]*?(\{[^}]*\})?\)/g)) {
        const [, base, opts = ''] = match
        if (!/communication:\s*false/.test(opts)) {
            routes.add(`${base}/communication`).add(`${base}/communication/inbox`).add(`${base}/communication/inbox/:conversationId`)
        }
        if (!/calendar:\s*false/.test(opts)) routes.add(`${base}/academic-calendar`)
        if (!/notifications:\s*false/.test(opts)) routes.add(`${base}/notifications`)
        if (/leaveKey:/.test(opts)) {
            routes.add(`${base}/leave-request/my-requests`).add(`${base}/leave-request/my-requests/add`).add(`${base}/leave-request/my-requests/view/:id`)
        }
    }
}
// Route helpers that build paths from a base: `Helper({ basePath: '/x' })` and `<StudentPortalRoutes routePrefix=... />`.
const templateSuffixes = (file, variable) =>
    [...readFileSync(file, 'utf8').matchAll(new RegExp(`path=\\{\`\\$\\{${variable}\\}([^\`]*)\``, 'g'))].map((m) => m[1])
const helpers = {
    TaskManagementRoutes: templateSuffixes(join(root, 'src', 'Common', 'TaskManagement', 'TaskManagementRoutes.jsx'), 'basePath'),
    StudentStarRatingsRoutes: templateSuffixes(join(root, 'src', 'Common', 'StudentStarRatings', 'StudentStarRatingsRoutes.jsx'), 'basePath'),
}
for (const file of routeFiles) {
    const text = readFileSync(file, 'utf8')
    for (const [helper, suffixes] of Object.entries(helpers)) {
        for (const match of text.matchAll(new RegExp(`${helper}\\(\\{\\s*basePath:\\s*'([^']+)'`, 'g'))) {
            for (const suffix of suffixes) routes.add(`${match[1]}${suffix}`)
        }
    }
}
// Route paths passed to StudentPortalRoutes as props (home fun, study materials, question bank, inbox).
for (const file of [
    join(root, 'src', 'Pages', 'Parent', 'parentPortalConfig.js'),
    join(root, 'src', 'Pages', 'Student', 'StudentDeliverables', 'studentDeliverablesConfig.js'),
    join(root, 'src', 'Routes', 'StudentRoutes.jsx'),
]) {
    const text = readFileSync(file, 'utf8')
    for (const m of text.matchAll(/_(?:ROUTE|COMMUNICATION_INBOX)\s*=\s*'([^']+)'/g)) routes.add(m[1])
    for (const m of text.matchAll(/communicationInboxBase=["']([^"']+)["']/g)) routes.add(m[1])
}
// StudentPortalRoutes serves both the student ('/student') and parent ('/parent') portals.
for (const prefix of ['/student', '/parent']) {
    for (const suffix of templateSuffixes(join(root, 'src', 'Routes', 'StudentPortalRoutes.jsx'), 'routePrefix')) {
        routes.add(`${prefix}${suffix}`)
    }
}
// Catch-all routes ('*') only redirect; they must not count as resolving a link. Template paths are expanded above.
const patterns = [...routes]
    .filter((path) => !path.includes('*') && !path.includes('$'))
    .map((path) => new RegExp(`^${path.replace(/:[^/]+/g, '[^/]+')}$`))
const resolves = (to) => {
    const path = String(to).split('?')[0].split('#')[0]
    return patterns.some((re) => re.test(path))
}

const collect = (links, out = []) => {
    for (const link of links || []) {
        // '#…' entries are collapsible group headers, not destinations.
        if (link?.to && !String(link.to).startsWith('#')) out.push({ to: link.to, label: link.label || link.title || link.name || '' })
        for (const key of ['children', 'subLinks', 'submenu', 'subMenu', 'items', 'links']) {
            if (Array.isArray(link?.[key])) collect(link[key], out)
        }
    }
    return out
}

const roles = sidebar.roleBasedSidebarLinks || {}
let problems = 0
for (const [role, links] of Object.entries(roles)) {
    const entries = collect(links)
    const missing = entries.filter((entry) => !resolves(entry.to))
    const seen = new Map()
    const duplicates = []
    for (const entry of entries) {
        if (seen.has(entry.to)) duplicates.push(entry)
        else seen.set(entry.to, entry)
    }
    if (missing.length || duplicates.length) {
        problems += missing.length + duplicates.length
        console.log(`\n[${role}] ${entries.length} links`)
        for (const entry of missing) console.log(`  MISSING ROUTE  ${entry.to}  (${entry.label})`)
        for (const entry of duplicates) console.log(`  DUPLICATE      ${entry.to}  (${entry.label})`)
    }
}
if (process.argv.includes('--coverage')) {
    // Which shared staff modules each role's menu offers (informational).
    const common = ['Task Management', 'Leave Request', 'Announcement', 'Communication', 'Calendar', 'Notifications', 'Report Issue / Escalation']
    const titles = (links) => (links || []).flatMap((l) => [l.title, ...titles(l.subLinks)])
    for (const [role, links] of Object.entries(roles)) {
        const all = titles(links)
        const missing = common.filter((t) => !all.some((x) => x === t || (t === 'Leave Request' && /Leave Request/.test(x || ''))))
        console.log(`${role.padEnd(24)} missing: ${missing.join(', ') || '-'}`)
    }
}
console.log(`\nroles=${Object.keys(roles).length} routes=${routes.size} problems=${problems}`)
process.exit(problems ? 1 : 0)
