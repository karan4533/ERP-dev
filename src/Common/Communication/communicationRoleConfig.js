export const getCommunicationRoleConfig = (roleKey) => {
    if (!roleKey) return undefined
    if (Object.prototype.hasOwnProperty.call(COMMUNICATION_ROLE_CONFIG, roleKey)) return COMMUNICATION_ROLE_CONFIG[roleKey]
    const clean = String(roleKey).toLowerCase().replace(/[-_\s]/g, '')
    if (Object.prototype.hasOwnProperty.call(COMMUNICATION_ROLE_CONFIG, clean)) return COMMUNICATION_ROLE_CONFIG[clean]
    return undefined
}
