export const getLogSummary = (logType, records = null) => {
    const items = records ?? getLogsByType(logType)

    switch (logType) {
        case 'login-history': {
            const successful = items.filter((r) => r.status === 'Success').length
            const uniqueUsers = new Set(items.map((r) => r.userEmail)).size
            return [
                { label: 'Total Entries', value: items.length },
                { label: 'Successful Logins', value: successful },
                { label: 'Unique Users', value: uniqueUsers },
                { label: 'Logouts', value: items.filter((r) => r.status === 'Logout').length },
            ]
        }
        case 'data-changes':
            return [
                { label: 'Total Changes', value: items.length },
                { label: 'Updates', value: items.filter((r) => r.changeType === 'Update').length },
                { label: 'Modules', value: new Set(items.map((r) => r.module)).size },
                { label: 'Users', value: new Set(items.map((r) => r.user)).size },
            ]
        case 'deleted-records':
            return [
                { label: 'Total Deleted', value: items.length },
                { label: 'Restorable', value: items.filter((r) => r.canRestore).length },
                { label: 'Modules', value: new Set(items.map((r) => r.module)).size },
                { label: 'Permanent', value: items.filter((r) => !r.canRestore).length },
            ]
        case 'approval-actions':
            return [
                { label: 'Total Actions', value: items.length },
                { label: 'Approved', value: items.filter((r) => r.action === 'Approved').length },
                { label: 'Rejected', value: items.filter((r) => r.action === 'Rejected').length },
                { label: 'Modules', value: new Set(items.map((r) => r.module)).size },
            ]
        case 'audit-logs':
            return [
                { label: 'Total Audits', value: items.length },
                { label: 'Completed', value: items.filter((r) => r.result === 'Completed').length },
                { label: 'In Progress', value: items.filter((r) => r.result === 'In Progress').length },
                { label: 'Auditors', value: new Set(items.map((r) => r.user)).size },
            ]
        case 'failed-logins':
            return [
                { label: 'Total Attempts', value: items.length },
                { label: 'Blocked', value: items.filter((r) => r.status === 'Blocked').length },
                { label: 'Failed', value: items.filter((r) => r.status === 'Failed').length },
                { label: 'Unique IPs', value: new Set(items.map((r) => r.ipAddress)).size },
            ]
        default:
            return []
    }
}

export const getLogStatusOptions = (records) => {
    const statuses = records
        .map((record) => record.status ?? record.action ?? record.result)
        .filter(Boolean)
    return [...new Set(statuses)].sort()
}

export const filterActivityLogs = (
    records,
    { search = '', status = '' } = {},
) => {
    const query = search.trim().toLowerCase()

    return records.filter((record) => {
        const recordStatus = record.status ?? record.action ?? record.result ?? ''
        if (status && recordStatus !== status) return false
        if (!query) return true

        return Object.values(record)
            .join(' ')
            .toLowerCase()
            .includes(query)
    })
}

